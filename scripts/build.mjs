import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const sources = ['time.js', 'settings.js', 'chatgpt-adapter.js', 'send-interceptor.js', 'content-entry.js'];
const chunks = [];
for (const name of sources) {
  const source = await readFile(new URL(`src/${name}`, root), 'utf8');
  chunks.push(`// src/${name}\n${source.replace(/^import .*?;\n/gm, '').replace(/^export /gm, '')}`);
}
const output = `// Generated by scripts/build.mjs. Edit src/, then run npm run build.\n(() => {\n'use strict';\n${chunks.join('\n')}\n})();\n`;
const destination = new URL('content.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('content.js is stale; run npm run build');
} else {
  await writeFile(destination, output);
  console.log(`Built ${fileURLToPath(destination)}`);
}
